"""Generates modules/discord/skins/discord-skin.css (the Discord module's docked-app skin) from Discord's own colour scales.

Usage (from tools/discord-skin): python -I gen_skin.py <discord css with the :root primitives> <google fonts css> <out.css>

Discord builds every theme token from primitive scales declared once on :root
(--neutral-N-hsl, --primary-N-hsl, --blurple-N-hsl, --opacity-N-hsl, --opacity-blurple-N-hsl).
Remapping those scales under the dark themes re-skins the whole app without touching any of
Discord's hashed class names, so it survives their frequent CSS rebuilds.
"""
import re
import sys

src, fonts_css, out = sys.argv[1:4]
s = open(src, encoding="utf8").read()
i = s.index(":root{--neutral-1:")
root = s[i:s.index("}", i)]


def scale(name):
    pat = r"--(" + name + r"-(\d+))-hsl:([^;]*)"
    rows = []
    for full, n, v in re.findall(pat, root):
        v = v.replace("calc(var(--saturation-factor, 1)*", "").replace(")", "")
        h, sat, l = v.split()
        rows.append((full, int(n), float(h), float(sat.rstrip("%")), float(l.rstrip("%"))))
    return sorted(rows, key=lambda r: r[1])


def lerp(points, x):
    if x <= points[0][0]:
        return points[0][1]
    for (x0, y0), (x1, y1) in zip(points, points[1:]):
        if x <= x1:
            return y0 + (y1 - y0) * (x - x0) / (x1 - x0)
    return points[-1][1]


# Grey scales (backgrounds at the dark end, text at the light end).
# Dark end → the Taken void the Command Center sits in: the base ~#050609, the chat ~#090a0f, panels
# ~#101218, so light (text, edges, the brand) is what stands out.
BG = [(0, 0), (15.5, 3.4), (18.4, 4.4), (21, 5.5), (22.7, 6.4), (23.9, 7.6), (25.3, 8.9), (26.5, 10.2), (33, 15.5), (39.4, 24), (45, 38)]
BG_SAT = [(0, 30), (8, 27), (20, 16), (40, 10)]
TX_SAT = [(40, 10), (85, 14), (95, 60), (100, 100)]


def grey(l):
    if l < 45:
        nl = lerp(BG, l)
        return 226, lerp(BG_SAT, nl), nl
    nl = l - 5 * (100 - l) / 55
    return 212, lerp(TX_SAT, nl), nl


# Blurple → Taken light. Fills (brand-500 buttons, badges) become a deep ice blue that keeps
# Discord's white text readable; the pale end (brand text, mentions) becomes #c9e9ff-ish.
def ice(l):
    t = min(max((l - 66) / 12, 0), 1)
    fill, pale = l * 0.66, l + (97 - l) * 0.5
    return 204, 75 * (1 - t) + 100 * t, fill * (1 - t) + pale * t


def fmt(h, sat, l):
    return f"{h:g} {sat:.1f}% {l:.2f}%"


def block(rows, fn):
    out = []
    for full, _, h, sat, l in rows:
        out.append(f"--{full}-hsl:{fmt(*fn(l))};--{full}:hsl(var(--{full}-hsl)/1)")
    return ";".join(out)


def reset(rows):
    return ";".join(f"--{full}-hsl:{fmt(h, sat, l)};--{full}:hsl(var(--{full}-hsl)/1)" for full, _, h, sat, l in rows)


neutral, primary, blurple = scale("neutral"), scale("primary"), scale("blurple")
opacity = [r for r in scale("opacity") if r[0].count("-") == 1]
opacity_bp = scale("opacity-blurple")
print(f"neutral {len(neutral)} primary {len(primary)} blurple {len(blurple)} opacity {len(opacity)} opacity-blurple {len(opacity_bp)}", file=sys.stderr)

overlay = ";".join(f"--{full}-hsl:210 30% 72%" for full, *_ in opacity)
overlay_bp = ";".join(f"--{full}-hsl:205 100% 81%" for full, *_ in opacity_bp)

# Google Fonts' @font-face rules (fonts.gstatic.com is allowed by Discord's font-src), minified.
faces = re.sub(r"/\*.*?\*/", "", open(fonts_css, encoding="utf8").read(), flags=re.S)
faces = re.sub(r"\s*([{};:,])\s*", r"\1", re.sub(r"\s+", " ", faces)).replace(";}", "}").strip()

# :not(#_) lifts specificity above Discord's own `.theme-dark{…}` blocks while matching the same elements.
DARK = ":is(.theme-dark,.theme-darker,.theme-midnight):not(#_)"
LIGHT = ".theme-light:not(#_)"

hand = open(__file__.replace("gen_skin.py", "skin_hand.css"), encoding="utf8").read().replace("DARK", DARK)

css = f"""/* Island skin for the docked Discord web app (embed.rs). GENERATED by gen_skin.py from Discord's
   primitive colour scales; hand-written part at the end. Dark themes only; light theme is left alone. */
{faces}
{DARK}{{{block(neutral, grey)};{block(primary, grey)};{block(blurple, ice)};{overlay};{overlay_bp}}}
{LIGHT}{{{reset(neutral)};{reset(primary)};{reset(blurple)}}}
{hand}"""
open(out, "w", encoding="utf8", newline="\n").write(css)
print(f"wrote {len(css)} bytes", file=sys.stderr)
